/**
 * Fetches ChessPal's piece sets from pinned sources and writes src/components/board/piece-svgs.ts.
 * SvgXml ignores <style> rules and gradients that inherit stops through href, so every SVG gets its
 * CSS inlined, its gradients flattened and its ids prefixed per piece, which keeps the 32 pieces
 * on one web page from sharing ids. Run `npm run pieces:build` after changing a source.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { format } from 'prettier';
import { optimize } from 'svgo';

import { PIECE_SETS, type PieceSetId } from '../../src/progress/types';

const LICHESS =
  'https://raw.githubusercontent.com/lichess-org/lila/22df4783c47a5715d40121b7e4641d67a1efffa2/public/piece';
const KOSAL =
  'https://raw.githubusercontent.com/philatype/kosal/fea676adb94de83e19834a2160b9f19ab94fd104';
const PIECE_NAMES = { K: 'king', Q: 'queen', R: 'rook', B: 'bishop', N: 'knight', P: 'pawn' };
const KEYS = (['w', 'b'] as const).flatMap((color) =>
  (Object.keys(PIECE_NAMES) as (keyof typeof PIECE_NAMES)[]).map((type) => ({ color, type })),
);

const SOURCES: Record<
  PieceSetId,
  { credit: string; url: (color: 'w' | 'b', type: keyof typeof PIECE_NAMES) => string }
> = {
  classic: {
    credit: 'Celtic by Maurizio Monge, MIT (licenses/celtic-mit.txt)',
    url: (color, type) => `${LICHESS}/celtic/${color}${type}.svg`,
  },
  modern: {
    credit: 'Kosal by philatype, CC BY 4.0 (licenses/kosal-cc-by-4.0.txt)',
    url: (color, type) => `${KOSAL}/${color === 'w' ? 'white' : 'black'}_${PIECE_NAMES[type]}.svg`,
  },
  wood: {
    credit: 'RhosGFX vector chess pieces, CC0 1.0 (licenses/rhosgfx-cc0.txt)',
    url: (color, type) => `${LICHESS}/rhosgfx/${color}${type}.svg`,
  },
};

/** Gives each gradient that borrows stops through href a copy of those stops. */
function flattenGradients(svg: string) {
  const stops = new Map<string, string>();
  for (const [, , , id, , inner] of svg.matchAll(
    /<(linearGradient|radialGradient)\b([^>]*?)\bid="([^"]+)"([^>]*?)(?<!\/)>([\s\S]*?)<\/\1>/g,
  ))
    stops.set(id, inner);
  return svg.replace(
    /<(linearGradient|radialGradient)\b([^>]*?)\/>/g,
    (whole, tag: string, attributes: string) => {
      const source = attributes.match(/(?:xlink:)?href="#([^"]+)"/)?.[1];
      if (!source || !stops.has(source)) return whole;
      const own = attributes.replace(/\s(?:xlink:)?href="#[^"]+"/, '');
      return `<${tag}${own}>${stops.get(source)}</${tag}>`;
    },
  );
}

function prepare(svg: string, prefix: string) {
  const { data } = optimize(flattenGradients(svg), {
    multipass: true,
    plugins: [
      {
        name: 'preset-default',
        params: { overrides: { inlineStyles: { onlyMatchedOnce: false } } },
      },
      'convertStyleToAttrs',
      { name: 'removeAttrs', params: { attrs: ['svg:style', 'svg:data-name', 'svg:id'] } },
      { name: 'prefixIds', params: { prefix, delim: '-' } },
    ],
  });
  if (/<style|class=|<(linear|radial)Gradient[^>]*href=/.test(data))
    throw new Error(`${prefix}: styles or gradient references survived conversion`);
  return data;
}

async function main() {
  const sets: Record<string, Record<string, string>> = {};
  for (const id of PIECE_SETS) {
    sets[id] = {};
    for (const { color, type } of KEYS) {
      const response = await fetch(SOURCES[id].url(color, type));
      if (!response.ok) throw new Error(`${id} ${color}${type}: ${response.status}`);
      sets[id][`${color}${type}`] = prepare(await response.text(), `${id}-${color}${type}`);
    }
    console.log(`${id}: ${Object.values(sets[id]).join('').length} characters`);
  }
  const credits = PIECE_SETS.map((id) => `// ${id}: ${SOURCES[id].credit}.`).join('\n');
  const source = `// Generated by scripts/pieces/build-piece-sets.ts from pinned sources; do not edit by hand.
${credits}
// Each SVG has its styles inlined, gradients flattened and ids prefixed; the artwork is unchanged.
export const pieceSvgs = ${JSON.stringify(sets, null, 2)} as const;
`;
  const output = resolve('src/components/board/piece-svgs.ts');
  writeFileSync(
    output,
    await format(source, {
      parser: 'typescript',
      ...(JSON.parse(readFileSync(resolve('.prettierrc'), 'utf8')) as object),
    }),
  );
  console.log(`Wrote ${output}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
